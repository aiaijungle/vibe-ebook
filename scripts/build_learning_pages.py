def lab(sec_id, kind, kicker, title, minutes, goal, easy, data, deep=None, pro=None, extra=''):
    blob = json.dumps(data, ensure_ascii=False).replace('</', '<\\/')
    parts = [
        f'<section class="aib-lab" data-lab="{kind}" id="{sec_id}" aria-labelledby="{sec_id}-t">',
        f'<p class="lab-kicker">{E(kicker)}</p><h2 id="{sec_id}-t">{E(title)}</h2>',
        f'<p class="lab-meta"><span>⏱ {minutes}분</span><span>🎯 {E(goal)}</span></p>',
        f'<p>{E(easy)}</p>', extra, '<div class="lab-mount"></div>',
    ]
    if deep:
        parts.append(f'<details class="lab-layer"><summary>한 단계 깊게 — {E(deep[0])}</summary><p>{E(deep[1])}</p></details>')
    if pro:
        parts.append(f'<details class="lab-layer"><summary>{E(pro[0])}</summary><p>{E(pro[1])}</p></details>')
    parts.append(f'<script type="application/json" class="lab-data">{blob}</script></section>')
    return '\n'.join(p for p in parts if p)


