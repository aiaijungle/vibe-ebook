def builder_data(fields, footer=None):
    checks = [{'key': f['key'], 'min': 4, 'ok': f['label'].split(' — ')[0] + ' 적음', 'todo': f['label'].split(' — ')[0] + ' 채우기'} for f in fields]
    d = {'fields': fields, 'checks': checks}
    if footer:
        d['footer'] = footer
    return d


def F(key, label, example, hint=None):
    f = {'key': key, 'label': label, 'example': example, 'placeholder': '예: ' + example[:40]}
    if hint:
        f['hint'] = hint
    return f


